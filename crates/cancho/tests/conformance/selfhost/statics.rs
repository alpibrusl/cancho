//! The modules of the command line in cancho that hold text: `guidelines.cho` (`AGENTS.md`) and `commandtree.cho` (what `cancho --help`,
//! `introspect` and `skill` say). A cancho string literal is one line, so a text is a function of appends to a buffer, a line each, in parts of forty
//! lines. The modules are generated; each test regenerates its module and fails if the committed file differs, and
//! `CANCHO_REGENERATE=1 cargo test statics` writes them again (`docs/cli-in-cancho.md` section 10 and 11).

use super::*;

/// One line of text as the body of a `console.write_all`: the escapes a cancho literal has, and no other control character.
fn literal(line: &str) -> String {
    let mut escaped = String::new();
    for c in line.chars() {
        match c {
            '\\' => escaped.push_str("\\\\"),
            '"' => escaped.push_str("\\\""),
            '\n' => escaped.push_str("\\n"),
            '\r' => escaped.push_str("\\r"),
            '\t' => escaped.push_str("\\t"),
            '\0' => escaped.push_str("\\0"),
            c if c.is_control() => panic!("a generated text holds a control character {c:?}"),
            c => escaped.push(c),
        }
    }
    escaped
}

/// `text` as functions that append it to a buffer, named `name_0`, `name_1`... and one `pub fn name` that calls them all.
fn writer(name: &str, text: &str) -> String {
    let lines: Vec<&str> = text.split_inclusive('\n').collect();
    let parts: Vec<&[&str]> = lines.chunks(40).collect();
    let mut out = String::new();
    for (n, part) in parts.iter().enumerate() {
        out.push_str(&format!("\nfn {name}_{n}[&h](heap: &!h Heap, out: buffer.Buffer) -> [heap] buffer.Buffer {{\n    var b = out;\n"));
        for line in *part {
            out.push_str(&format!("    b = buffer.append(heap, b, \"{}\");\n", literal(line)));
        }
        out.push_str("    return b;\n}\n");
    }
    out.push_str(&format!("\npub fn {name}[&h](heap: &!h Heap, out: buffer.Buffer) -> [heap] buffer.Buffer {{\n    var b = out;\n"));
    for n in 0..parts.len() {
        out.push_str(&format!("    b = {name}_{n}(heap, b);\n"));
    }
    out.push_str("    return b;\n}\n");
    out
}

fn header(module: &str, what: &str, test: &str) -> String {
    format!(
        "edition 7;\nmodule selfhost.{module};\n\n// {module}.cho -- {what} (`docs/cli-in-cancho.md`).\n// GENERATED by the test `selfhost::statics::{test}`: change the source, then run it with CANCHO_REGENERATE=1.\n\nimport std.buffer;\n"
    )
}

fn check(file: &str, want: &str, test: &str) {
    let module = repo_root().join("examples/selfhost").join(file);
    if std::env::var_os("CANCHO_REGENERATE").is_some() {
        std::fs::write(&module, want).expect("the module is written");
    }
    let have = std::fs::read_to_string(&module).expect("the module is read");
    assert!(
        have == want,
        "{file} is not what {test} generates: run it with CANCHO_REGENERATE=1 and commit the result"
    );
}

/// What `cancho` writes for `arguments`: the standard output, which a text of this module must be.
fn said(arguments: &[&str]) -> String {
    // Run from a scratch directory: `introspect` and `skill` of the Rust binary write a `.cli/` directory beside where they are run.
    let run = Command::new(BIN)
        .current_dir(scratch("selfhost-said"))
        .args(arguments)
        .output()
        .expect("cancho runs");
    assert!(run.status.success(), "`cancho {}` failed", arguments.join(" "));
    String::from_utf8(run.stdout).expect("the text is UTF-8")
}

pub(super) fn guidelines_text() -> String {
    std::fs::read_to_string(repo_root().join("AGENTS.md")).expect("AGENTS.md is read")
}

#[test]
fn guidelines_module_is_the_text_of_agents_md() {
    let want = header(
        "guidelines",
        "the text of `AGENTS.md`, for `cancho agent-guidelines`",
        "guidelines_module_is_the_text_of_agents_md",
    ) + &writer("print", &guidelines_text());
    check("guidelines.cho", &want, "guidelines_module_is_the_text_of_agents_md");
}

/// The texts `introspect` and `skill` write are the command tree of the Rust binary (`src/acli.rs`), in the three forms of the ACLI library.
#[test]
fn command_tree_module_is_what_cancho_says() {
    let mut want = header(
        "commandtree",
        "what `cancho --help`, `introspect` and `skill` write",
        "command_tree_module_is_what_cancho_says",
    );
    for (name, arguments) in [
        ("usage", vec!["--help"]),
        ("introspect_text", vec!["introspect"]),
        ("introspect_json", vec!["introspect", "--output", "json"]),
        ("introspect_table", vec!["introspect", "--output", "table"]),
        ("skill_text", vec!["skill"]),
    ] {
        want.push_str(&writer(name, &said(&arguments)));
    }
    // `skill --output json` answers the path it was given, or `null`: the text is cut where the value goes.
    let json = said(&["skill", "--output", "json"]);
    let at = json.find("\"path\": null").expect("the answer has a path") + "\"path\": ".len();
    want.push_str(&writer("skill_json_head", &json[..at]));
    want.push_str(&writer("skill_json_tail", &json[at + "null".len()..]));
    check("commandtree.cho", &want, "command_tree_module_is_what_cancho_says");
}

/// The standard library files in the order `cancho --std` adds them to a program (`STD` in `crates/cancho/src/main.rs`), as the module
/// `stdorder.cho`: the names, each followed by a NUL. The order is the order of the identities `cancho ids --std` writes.
#[test]
fn std_order_module_is_the_std_table_of_cancho() {
    let main = std::fs::read_to_string(repo_root().join("crates/cancho/src/main.rs"))
        .expect("main.rs is read");
    let table = main
        .split("const STD: &[(&str, &str)] = &[")
        .nth(1)
        .expect("the STD table")
        .split("];")
        .next()
        .expect("its end");
    let names: Vec<&str> = table
        .lines()
        .filter_map(|l| l.trim().strip_prefix("(\"<std>/")?.split(".cho\"").next())
        .collect();
    assert!(names.len() > 40, "only {} names in the STD table", names.len());
    // Every file of `std/` is in it, and nothing else is.
    let mut on_disk: Vec<String> = std::fs::read_dir(repo_root().join("std"))
        .expect("std/ is read")
        .filter_map(|e| e.ok()?.file_name().to_str()?.strip_suffix(".cho").map(str::to_owned))
        .collect();
    on_disk.sort();
    let mut listed: Vec<String> = names.iter().map(|n| (*n).to_owned()).collect();
    listed.sort();
    assert_eq!(listed, on_disk, "the STD table and std/");
    let mut text = String::new();
    for name in &names {
        text.push_str(&format!("{name}\n"));
    }
    let want = header(
        "stdorder",
        "the standard library's files, in the order `--std` adds them",
        "std_order_module_is_the_std_table_of_cancho",
    ) + &writer("names", &text.replace('\n', "\0"));
    check("stdorder.cho", &want, "std_order_module_is_the_std_table_of_cancho");
}
