#!/usr/bin/env python3
"""Generates packages/secp256k1/comb.cho, the generator's comb table for `secp256k1` (docs/secp256k1.md section 2).

    python3 scripts/secp256k1_tables.py > packages/secp256k1/comb.cho
    python3 scripts/secp256k1_tables.py --check        # fails when the file is not what this prints

Entry (i, j), i in 0..64 and j in 0..16, is the affine point j * 16^i * G (entry j = 0 is G, never used: a zero digit adds nothing), its x then its
y as four 64-bit limbs each, least significant first, in Montgomery form (value * 2^256 mod p), the form `std.bigmod` keeps its registers in.
Each 64-bit limb is stored as two words, its low half then its high half, each 8 hex digits and below 2^32, so decoding a `static` needs nothing wider than an
`int` (the Rust evaluator refuses `wrapping_*` in a `static`, and a plain product of a high half by 2^32 would overflow); `comb_select` joins the halves at run
time, after the masked selection.
"""
import os, sys

P = 2**256 - 2**32 - 977
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
G = (0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798, 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8)
R = 2**256 % P


def add(a, b):
    if a is None: return b
    if b is None: return a
    if a[0] == b[0] and (a[1] + b[1]) % P == 0: return None
    if a == b:
        l = 3 * a[0] * a[0] * pow(2 * a[1], -1, P) % P
    else:
        l = (b[1] - a[1]) * pow(b[0] - a[0], -1, P) % P
    x = (l * l - a[0] - b[0]) % P
    return (x, (l * (a[0] - x) - a[1]) % P)


def mul(k, p):
    r = None
    while k:
        if k & 1: r = add(r, p)
        p = add(p, p)
        k >>= 1
    return r


def limbs(v):
    m = v * R % P
    return [(m >> (64 * i)) & (2**64 - 1) for i in range(4)]


def table():
    words = []
    base = G
    for i in range(64):
        for j in range(16):
            pt = mul(j, base) if j else G
            for c in pt:
                words.extend(limbs(c))
        base = mul(16, base)
    return words


def render():
    t = table()
    halves = []
    for w in t:
        halves.extend([w & 0xFFFFFFFF, w >> 32])
    lit = "".join("%08x" % h for h in halves)
    n = len(halves)
    return f'''module secp256k1_comb;

// GENERATED by `scripts/secp256k1_tables.py`; do not edit. `python3 scripts/secp256k1_tables.py --check` fails when this file is not what the
// script prints.
//
// `secp256k1_comb` -- the generator's comb for `secp256k1` (`docs/secp256k1.md` §2): affine points, x then y, each coordinate in Montgomery form
// (value * 2^256 mod p) as four 64-bit limbs, least significant first, each as two 32-bit words, low half first. Entry (i, j) is j * 16^i * G for i in 0..64
// and j in 0..16 (entry 0 is G and is never used), at word (16 i + j) * 16. A `static` is evaluated while compiling and is read-only data in the binary
// (`docs/compile-time-data.md`): nothing is built when a program runs.

pub static comb: [int] {{
    let t = alloc_slice[static]({n}, 0);
    let s = "{lit}";
    var i = 0;
    while i < {n} {{
        var v = 0;
        var j = 0;
        while j < 8 {{
            let c = int_of(s[8 * i + j]);
            v = v * 16 + (c >> 6) * 9 + (c & 15);
            j = j + 1;
        }}
        t[i] = v;
        i = i + 1;
    }}
    return t;
}}

// The 16 words of entry (i, j): the low and high halves of its eight limbs, x's four then y's four.
pub fn row(i: int, j: int) -> [] &static [int] {{
    let at = (16 * i + j) * 16;
    return comb[at..at + 16];
}}
'''


if __name__ == "__main__":
    out = render()
    if "--check" in sys.argv:
        path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "packages/secp256k1/comb.cho")
        sys.exit(0 if open(path).read() == out else 1)
    sys.stdout.write(out)
