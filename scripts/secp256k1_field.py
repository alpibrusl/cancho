#!/usr/bin/env python3
"""Generates packages/secp256k1/field.cho, unrolled Montgomery multiplication, addition and subtraction modulo p = 2^256 - 2^32 - 977 (docs/secp256k1.md section 4).

    python3 scripts/secp256k1_field.py > packages/secp256k1/field.cho
    python3 scripts/secp256k1_field.py --check        # fails when the file is not what this prints

It is `std.bigmod`'s `mont_mul` for four 64-bit limbs with the loops written out and the limbs in locals instead of slices of the work area, so the same
registers, the same Montgomery form (R = 2^256) and the same answer (below p) hold. `scripts/secp256k1_differential.py` is what says so.
"""
import os, sys

P = 2**256 - 2**32 - 977
NINV = (-pow(P, -1, 2**64)) % 2**64


def signed(v):
    return v - 2**64 if v >= 2**63 else v


def mul_lines(P, doc):
    NINV = (-pow(P, -1, 2**64)) % 2**64
    n = [(P >> (64 * i)) & (2**64 - 1) for i in range(4)]
    L = []
    e = L.append
    e(doc)
    e("pub fn mul[&w](w: &!w [int], x: int, y: int, dst: int) -> [] int {")
    for i in range(4):
        e(f"    let x{i} = w[x + {i}];")
    for i in range(4):
        e(f"    let y{i} = w[y + {i}];")
    for i in range(5):
        e(f"    var t{i} = 0;")
    e("    var ca = 0;")
    e("    var cm = 0;")
    for i in range(4):
        e(f"    // limb {i} of x")
        e(f"    let (h{i}0, l{i}0) = mul_wide(x{i}, y0);")
        e(f"    let (u{i}0, k{i}0) = add_carry(t0, l{i}0, 0);")
        e(f"    ca = wrapping_add(h{i}0, k{i}0);")
        e(f"    let m{i} = wrapping_mul(u{i}0, {signed(NINV)});")
        e(f"    let (g{i}0, q{i}0) = mul_wide(m{i}, {signed(n[0])});")
        e(f"    let (z{i}0, kz{i}) = add_carry(u{i}0, q{i}0, 0);")
        e(f"    cm = wrapping_add(g{i}0, kz{i});")
        for j in range(1, 4):
            e(f"    let (h{i}{j}, l{i}{j}) = mul_wide(x{i}, y{j});")
            e(f"    let (u{i}{j}, ka{i}{j}) = add_carry(t{j}, l{i}{j}, 0);")
            e(f"    let (v{i}{j}, kb{i}{j}) = add_carry(u{i}{j}, ca, 0);")
            e(f"    ca = wrapping_add(wrapping_add(h{i}{j}, ka{i}{j}), kb{i}{j});")
            e(f"    let (g{i}{j}, q{i}{j}) = mul_wide(m{i}, {signed(n[j])});")
            e(f"    let (r{i}{j}, kc{i}{j}) = add_carry(v{i}{j}, q{i}{j}, 0);")
            e(f"    let (s{i}{j}, kd{i}{j}) = add_carry(r{i}{j}, cm, 0);")
            e(f"    cm = wrapping_add(wrapping_add(g{i}{j}, kc{i}{j}), kd{i}{j});")
            e(f"    t{j - 1} = s{i}{j};")
        e(f"    let (w{i}a, kw{i}) = add_carry(t4, ca, 0);")
        e(f"    let (w{i}b, kx{i}) = add_carry(w{i}a, cm, 0);")
        e(f"    t3 = w{i}b;")
        e(f"    t4 = kw{i} + kx{i};")
    e("    // t is below 2p: take p off, unless that goes below zero, without a branch.")
    for j in range(4):
        e(f"    let (d{j}, b{j}) = sub_borrow(t{j}, {signed(n[j])}, {'0' if j == 0 else f'b{j-1}'});")
    e("    let (dz, b4) = sub_borrow(t4, 0, b3);")
    e("    let keep = value_barrier(0 - b4);")
    for j in range(4):
        e(f"    w[dst + {j}] = t{j} & keep | d{j} & (keep ^ -1);")
    e("    w[dst + 4] = 0;")
    e("    return 0;")
    e("}")
    return L


def render():
    n = [(P >> (64 * i)) & (2**64 - 1) for i in range(4)]
    L = mul_lines(P, "// x * y / 2^256 mod p, for registers x, y and dst of the work area `w` (four limbs each; dst may be x or y). Below p.")
    e = L.append
    e("")
    e("// a + b mod p, for registers a, b and dst (dst may be a or b). Below p.")
    e("pub fn add[&w](w: &!w [int], a: int, b: int, dst: int) -> [] int {")
    for j in range(4):
        e(f"    let (s{j}, c{j}) = add_carry(w[a + {j}], w[b + {j}], {'0' if j == 0 else f'c{j-1}'});")
    for j in range(4):
        e(f"    let (d{j}, b{j}) = sub_borrow(s{j}, {signed(n[j])}, {'0' if j == 0 else f'b{j-1}'});")
    e("    // a + b is below 2p: p comes off when the sum carried out of 256 bits or is p or more.")
    e("    let take = value_barrier(0 - (c3 | b3 ^ 1));")
    for j in range(4):
        e(f"    w[dst + {j}] = d{j} & take | s{j} & (take ^ -1);")
    e("    w[dst + 4] = 0;")
    e("    return 0;")
    e("}")
    e("")
    e("// a - b mod p, for registers a, b and dst (dst may be a or b). Below p.")
    e("pub fn sub[&w](w: &!w [int], a: int, b: int, dst: int) -> [] int {")
    for j in range(4):
        e(f"    let (d{j}, b{j}) = sub_borrow(w[a + {j}], w[b + {j}], {'0' if j == 0 else f'b{j-1}'});")
    e("    // below zero: p goes back on, under a mask made from the borrow; the carry out is the borrow it cancels.")
    e("    let m = value_barrier(0 - b3);")
    for j in range(4):
        e(f"    let (r{j}, k{j}) = add_carry(d{j}, {signed(n[j])} & m, {'0' if j == 0 else f'k{j-1}'});")
        e(f"    w[dst + {j}] = r{j};")
    e("    w[dst + 4] = 0;")
    e("    return 0;")
    e("}")
    body = "\n".join(L)
    return f'''edition 7;
module secp256k1_field;

// GENERATED by `scripts/secp256k1_field.py`; do not edit. `python3 scripts/secp256k1_field.py --check` fails when this file is not what the script
// prints.
//
// `secp256k1_field` -- Montgomery multiplication, addition and subtraction modulo p = 2^256 - 2^32 - 977 with the four limbs in locals (`docs/secp256k1.md` §2): the loops of
// `std.bigmod`'s `mont_mul` written out for k = 4. Registers are `std.bigmod`'s (each `reg(i)` is an offset into `w`, four limbs, least significant
// first, in Montgomery form with R = 2^256), so `bigmod.add`, `bigmod.sub` and the conversions work on its results unchanged. Straight-line code:
// nothing branches on a value or indexes by one. p, -p^-1 mod 2^64 and the limbs of p are written here as the signed words they are.

{body}
'''


N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141


def render_scalar():
    body = "\n".join(mul_lines(N, "// x * y / 2^256 mod n, n the group order, for registers x, y and dst of the work area `w`. Below n."))
    return f'''edition 7;
module secp256k1_scalar;

// GENERATED by `scripts/secp256k1_field.py --scalar`; do not edit. `python3 scripts/secp256k1_field.py --scalar --check` fails when this file is not
// what the script prints.
//
// `secp256k1_scalar` -- Montgomery multiplication modulo the group order n with the four limbs in locals (`docs/secp256k1.md` §2): the same code as
// `secp256k1_field.mul` with n and -n^-1 mod 2^64 in place of p's. Registers are `std.bigmod`'s, set up modulo n, in Montgomery form with R = 2^256.

{body}
'''


if __name__ == "__main__":
    scalar = "--scalar" in sys.argv
    out = render_scalar() if scalar else render()
    if "--check" in sys.argv:
        path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "packages/secp256k1/" + ("scalar.cho" if scalar else "field.cho"))
        sys.exit(0 if open(path).read() == out else 1)
    sys.stdout.write(out)
