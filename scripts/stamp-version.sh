#!/bin/sh
# Write examples/selfhost/version.cho for a release build: the commit this command line is built from and the machine it is built on.
#
#   scripts/stamp-version.sh COMMIT [HOST]
#
#   COMMIT  the full commit hash (40 or 64 lowercase hex digits), with `-dirty` after it for a tree that differs; the value `cancho = "..."` is compared with
#   HOST    the host triple `--version` prints (default: from `uname -sm`: x86_64-unknown-linux-gnu, aarch64-unknown-linux-gnu or aarch64-apple-darwin)
#
# VERSION_CHO names another file to write (a test stamps a copy).
# The crate version is read from crates/cancho/Cargo.toml, as `--version` of the Rust command line reads it. Anything that is not a commit is refused:
# a stamp that a typo makes wrong would make every pinned project refuse (or, worse, accept) this compiler.
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
rev=${1:-}
[ -n "$rev" ] || { echo "usage: stamp-version.sh COMMIT [HOST]" >&2; exit 2; }
hash=${rev%-dirty}
case $hash in
  *[!0-9a-f]*|'') echo "not a full commit hash: $rev" >&2; exit 2 ;;
esac
[ "${#hash}" -eq 40 ] || [ "${#hash}" -eq 64 ] || { echo "not a full commit hash: $rev" >&2; exit 2; }
if [ -n "${2:-}" ]; then
  host=$2
else
  case "$(uname -s)-$(uname -m)" in
    Linux-x86_64)  host=x86_64-unknown-linux-gnu ;;
    Linux-aarch64) host=aarch64-unknown-linux-gnu ;;
    Darwin-arm64)  host=aarch64-apple-darwin ;;
    *) echo "no host triple for $(uname -s)-$(uname -m); pass one" >&2; exit 3 ;;
  esac
fi
case $host in
  *[!0-9a-z_.-]*|'') echo "not a host triple: $host" >&2; exit 2 ;;
esac
version=$(sed -n 's/^version *= *"\([0-9][0-9.]*\)".*/\1/p' "$here/crates/cancho/Cargo.toml" | head -1)
[ -n "$version" ] || version=$(sed -n 's/^version *= *"\([0-9][0-9.]*\)".*/\1/p' "$here/Cargo.toml" | head -1)
[ -n "$version" ] || { echo "no version in Cargo.toml" >&2; exit 3; }
out=${VERSION_CHO:-$here/examples/selfhost/version.cho}
cat > "$out" <<EOF
edition 7;
module selfhost.version;

// version.cho -- the crate version, the commit and the machine a command line was built from, for \`--version\` and the compiler pin (\`docs/standalone-cancho.md\` D2).
// GENERATED by \`scripts/stamp-version.sh\` in a release build, which writes the commit and the host. The repository carries the unstamped form: \`unknown\`,
// the word \`crates/cancho/build.rs\` uses when there is no git checkout and no \`CANCHO_REV\`.

pub fn crate_version() -> [] &static [byte] {
    return "$version";
}

pub fn rev() -> [] &static [byte] {
    return "$rev";
}

pub fn host() -> [] &static [byte] {
    return "$host";
}
EOF
